// gen-redirects.mjs — one-time generator for redirects.mjs (imported by worker.js).
//
// The live legacy site serves ~186 URL shapes the June-8 mirror stores under
// different paths (long QMI URLs with numeric ids, per-community floor-plan ids
// that drifted, /new-homes/tx/<city>/ city stubs). This maps each one onto the
// mirror page that carries the same content, so every live URL keeps resolving
// after DNS cutover.
//
//   node scripts/gen-redirects.mjs <live-404-paths.txt> <mirror-pages.txt>
//
// live-404-paths.txt: URLs that are 200 on live but 404 on the mirror (one path
// per line; already-scraped pages are skipped because they now exist in public/).
// mirror-pages.txt: every page path the mirror serves. Writes ./redirects.mjs.
import fs from 'node:fs';
import { join } from 'node:path';

const [live404File, mirrorFile] = process.argv.slice(2);
const ROOT = join(import.meta.dirname, '..');
const live404 = fs.readFileSync(live404File, 'utf8').trim().split('\n');
const mirror = new Set(fs.readFileSync(mirrorFile, 'utf8').trim().split('\n'));

// Slug comparison that survives cosmetic drift: 'retama-village-(55-)-at-bentsen-palm'
// vs 'retama-village-55-at-bentsen-palm'.
const key = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, '');
// Address comparison: expand common street-suffix abbreviations token-wise, so
// '1413-zurich-ave' matches '1413-zurich-avenue'.
const SUFFIX = { ave: 'avenue', st: 'street', dr: 'drive', ln: 'lane', rd: 'road', ct: 'court', blvd: 'boulevard', cir: 'circle', pl: 'place', trl: 'trail', pkwy: 'parkway', hwy: 'highway', ter: 'terrace' };
const addrKey = (s) => s.toLowerCase().split(/[^a-z0-9]+/).filter(Boolean).map(t => SUFFIX[t] || t).join('');

// Index the mirror's /new-homes/tx/ tree.
const comms = new Map();   // cityKey|commKey -> community page path
const qmis = new Map();    // cityKey|commKey -> [{addrKey, path}]
const plans = new Map();   // cityKey|commKey|planKey -> fp page path
const globalPlans = new Map(); // planKey -> /floorplans/<plan>/
for (const p of mirror) {
  let m;
  if ((m = p.match(/^\/floorplans\/([^/]+)\/$/))) { globalPlans.set(key(m[1]), p); continue; }
  if (!(m = p.match(/^\/new-homes\/tx\/([^/]+)\/([^/]+)(?:\/([^/]+))?(?:\/(\d+))?\/$/))) continue;
  const [, city, comm, seg3, seg4] = m;
  const ck = key(city) + '|' + key(comm);
  if (!seg3) { comms.set(ck, p); continue; }
  if (seg4) { plans.set(ck + '|' + key(seg3), p); continue; }
  if (!/^\d+$/.test(seg3)) (qmis.get(ck) || qmis.set(ck, []).get(ck)).push({ ak: addrKey(seg3), path: p });
}

const redirects = {};
const report = [];
const commOr = (ck, city) => comms.get(ck) || (mirror.has(`/${city}/`) ? `/${city}/` : '/new-homes/');
for (const p of live404) {
  // Skip anything a scraped page now covers.
  if (fs.existsSync(join(ROOT, 'public', p, 'index.html'))) continue;
  let m, to, why;
  if ((m = p.match(/^\/new-homes\/tx\/([^/]+)\/$/))) {
    // City stub (404s on live too); upgrade to the mirror's city page.
    to = `/${m[1]}/`; why = 'city';
  } else if ((m = p.match(/^\/new-homes\/tx\/([^/]+)\/([^/]+)\/\d+\/([^/]+)\/\d+\/$/))) {
    // Long QMI URL -> short QMI page (fuzzy address), else community page.
    const [, city, comm, addr] = m;
    const ck = key(city) + '|' + key(comm);
    const hit = (qmis.get(ck) || []).find(q => q.ak === addrKey(addr));
    to = hit?.path || commOr(ck, city);
    why = hit ? 'qmi' : 'qmi-unmatched->community';
  } else if ((m = p.match(/^\/new-homes\/tx\/([^/]+)\/([^/]+)\/([^/]+)\/\d+\/$/))) {
    // Per-community floor plan with a drifted numeric id -> mirror's copy of the
    // same plan in that community, else the global plan page, else community.
    const [, city, comm, plan] = m;
    const ck = key(city) + '|' + key(comm);
    to = plans.get(ck + '|' + key(plan)) || globalPlans.get(key(plan))
      || (qmis.get(ck) || []).find(q => q.ak === addrKey(plan))?.path || commOr(ck, city);
    why = plans.has(ck + '|' + key(plan)) ? 'fp-community' : globalPlans.has(key(plan)) ? 'fp-global' : 'fp-unmatched->community';
  } else if ((m = p.match(/^\/new-homes\/tx\/([^/]+)\/([^/]+)\/\d+\/$/))) {
    // Bare community-id page -> community page.
    to = commOr(key(m[1]) + '|' + key(m[2]), m[1]); why = 'community-id';
  } else {
    report.push(`SKIP (no rule) ${p}`);
    continue;
  }
  if (!mirror.has(to) && !fs.existsSync(join(ROOT, 'public', to, 'index.html'))) {
    report.push(`BROKEN TARGET ${p} -> ${to}`);
    continue;
  }
  redirects[p] = to;
  report.push(`${why} ${p} -> ${to}`);
}

const body = '// redirects.mjs — GENERATED by scripts/gen-redirects.mjs; maps legacy live-site\n' +
  '// URL shapes onto their mirror equivalents (301). Do not hand-edit entries.\n' +
  'export const REDIRECTS = ' + JSON.stringify(redirects, null, 1) + ';\n';
fs.writeFileSync(join(ROOT, 'redirects.mjs'), body);
fs.writeFileSync('/tmp/redirects-report.txt', report.join('\n') + '\n');
const counts = {};
for (const r of report) counts[r.split(' ')[0]] = (counts[r.split(' ')[0]] || 0) + 1;
console.log(`wrote redirects.mjs: ${Object.keys(redirects).length} entries`, counts);
